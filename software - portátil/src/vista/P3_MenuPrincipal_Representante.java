    private void cargarDiaEncuesta() {

    modelo.GastosDiariosDAO dao = new modelo.GastosDiariosDAO();

    int dia = dao.obtenerDiaEncuesta(SesionUsuario.getCedula());

    if (dia >= 1 && dia <= 14) {
        lblDia.setText(String.valueOf(dia));
    } else {
        lblDia.setText("-");
    }
}
    
