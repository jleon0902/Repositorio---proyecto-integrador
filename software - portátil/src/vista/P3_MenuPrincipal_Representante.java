    private void registrarCapitulos() {
    javax.swing.JLabel mensaje = new javax.swing.JLabel(
        "¿Cuántos productos desea registrar?"
    );

    mensaje.setAlignmentX(java.awt.Component.CENTER_ALIGNMENT);

    // Permitir seleccionar únicamente cantidades enteras entre 1 y 10.
    javax.swing.JSpinner cantidad = new javax.swing.JSpinner(
        new javax.swing.SpinnerNumberModel(1, 1, 10, 1)
    );

    // Configurar el campo para rechazar letras, símbolos y decimales.
    javax.swing.JSpinner.NumberEditor editor =
            new javax.swing.JSpinner.NumberEditor(cantidad, "0");

    cantidad.setEditor(editor);

    javax.swing.JFormattedTextField campoCantidad =
            editor.getTextField();

    javax.swing.text.NumberFormatter formato =
            (javax.swing.text.NumberFormatter) campoCantidad.getFormatter();

    formato.setValueClass(Integer.class);
    formato.setMinimum(1);
    formato.setMaximum(10);
    formato.setAllowsInvalid(false);
    formato.setCommitsOnValidEdit(true);

    cantidad.setMaximumSize(new java.awt.Dimension(100, 30));
    cantidad.setAlignmentX(java.awt.Component.CENTER_ALIGNMENT);

    javax.swing.JPanel panel = new javax.swing.JPanel();
    panel.setLayout(new javax.swing.BoxLayout(
        panel, javax.swing.BoxLayout.Y_AXIS
    ));

    panel.add(mensaje);
    panel.add(javax.swing.Box.createVerticalStrut(15));
    panel.add(cantidad);

    Object[] botones = {"Cancelar", "Continuar"};

    int opcion = javax.swing.JOptionPane.showOptionDialog(
        this,
        panel,
        "Registrar capítulos",
        javax.swing.JOptionPane.DEFAULT_OPTION,
        javax.swing.JOptionPane.QUESTION_MESSAGE,
        null,
        botones,
        botones[1]
    );

    if (opcion == 1) {
    int cantidadSeleccionada = (Integer) cantidad.getValue();
    controlador.abrirGastosDiarios(cantidadSeleccionada);
    }
}
    
