// Gestiona el inicio de sesión.
private void iniciarSesion() {

    String usuario = txt_campousuario.getText().trim();
    String contrasena = txt_campocontraseña.getText();

    if (usuario.isEmpty() || contrasena.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Ingrese el usuario y la contraseña.");

        return;
    }

    String[] resultado = controlador.iniciarSesion(
            usuario, contrasena
    );

    // Comprobar si ocurrió un error de conexión.
    if (controlador.huboErrorConexion()) {

        JOptionPane.showMessageDialog(this,
                "No fue posible conectar con la base de datos.",
                "Error de conexión",
                JOptionPane.ERROR_MESSAGE);

        return;
    }

    // Comprobar credenciales incorrectas.
    if (resultado == null) {

        JOptionPane.showMessageDialog(this,
                "Usuario o contraseña incorrectos.",
                "Acceso denegado",
                JOptionPane.ERROR_MESSAGE);

        txt_campocontraseña.setText("");

        return;
    }

    JOptionPane.showMessageDialog(this,
            "Inicio de sesión exitoso.");

    if ("REPRESENTANTE".equalsIgnoreCase(resultado[0])) {

    main.mostrarMenuRepresentante();
    this.dispose();

    } else if ("ENCUESTADOR".equalsIgnoreCase(resultado[0])) {

    main.mostrarMenuEncuestador();
    this.dispose();

    } else {

        JOptionPane.showMessageDialog(this,
                "Tipo de persona no reconocido.",
                "Error de acceso",
                JOptionPane.ERROR_MESSAGE);
    }
}

