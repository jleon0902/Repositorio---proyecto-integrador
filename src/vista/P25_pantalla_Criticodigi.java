private void mostrarGrafica() {

    // Crear los datos de la gráfica
    org.jfree.data.category.DefaultCategoryDataset datos =
            new org.jfree.data.category.DefaultCategoryDataset();

    // Porcentajes de ejemplo: suman 100 %
    datos.addValue(30, "Porcentaje", "Compra");
    datos.addValue(20, "Porcentaje", "Recibidos como pago por trabajo");
    datos.addValue(15, "Porcentaje", "Regalo o donación");
    datos.addValue(10, "Porcentaje", "Intercambio o trueque");
    datos.addValue(10, "Porcentaje", "Traídos de la finca o producidos por el hogar");
    datos.addValue(5, "Porcentaje", "Tomados de un negocio del hogar");
    datos.addValue(10, "Porcentaje", "Otros");

    // Crear la gráfica de barras horizontales
    org.jfree.chart.JFreeChart grafica =
            org.jfree.chart.ChartFactory.createBarChart(
                    "Formas de adquisición",
                    "Porcentaje",
                    "Forma de adquisición",
                    datos,
                    org.jfree.chart.plot.PlotOrientation.HORIZONTAL,
                    false,
                    true,
                    false
            );

    // Configurar el área de la gráfica
    org.jfree.chart.plot.CategoryPlot plot =
            grafica.getCategoryPlot();

    plot.setBackgroundPaint(java.awt.Color.WHITE);
    plot.setOutlineVisible(false);
    plot.setRangeGridlinePaint(java.awt.Color.LIGHT_GRAY);

    // Asignar un color diferente a cada barra
    org.jfree.chart.renderer.category.BarRenderer renderer =
            new org.jfree.chart.renderer.category.BarRenderer() {

        private final java.awt.Color[] colores = {
            new java.awt.Color(52, 152, 219),
            new java.awt.Color(46, 204, 113),
            new java.awt.Color(241, 196, 15),
            new java.awt.Color(231, 76, 60),
            new java.awt.Color(155, 89, 182),
            new java.awt.Color(230, 126, 34),
            new java.awt.Color(127, 140, 141)
        };

        @Override
        public java.awt.Paint getItemPaint(int fila, int columna) {
            return colores[columna % colores.length];
        }
    };

    // Mostrar el porcentaje al final de cada barra
    renderer.setDefaultItemLabelsVisible(true);

    renderer.setDefaultItemLabelGenerator(
            new org.jfree.chart.labels.StandardCategoryItemLabelGenerator(
                    "{2}%",
                    java.text.NumberFormat.getNumberInstance()
            )
    );

    plot.setRenderer(renderer);

    // Ajustar las etiquetas de las categorías
    plot.getDomainAxis().setTickLabelFont(
            new java.awt.Font("Arial", java.awt.Font.PLAIN, 10)
    );

    // Crear el panel de la gráfica
    org.jfree.chart.ChartPanel panelGrafica =
            new org.jfree.chart.ChartPanel(grafica);

    panelGrafica.setPreferredSize(
            new java.awt.Dimension(680, 360)
    );

    panelGrafica.setMaximumDrawWidth(680);
    panelGrafica.setMaximumDrawHeight(360);
    panelGrafica.setMinimumDrawWidth(500);
    panelGrafica.setMinimumDrawHeight(280);

    // Colocar la gráfica en jPanel3
    pnlMuestreo.setLayout(new java.awt.BorderLayout());
    pnlMuestreo.removeAll();

    pnlMuestreo.setPreferredSize(
            new java.awt.Dimension(680, 360)
    );

    pnlMuestreo.add(panelGrafica, java.awt.BorderLayout.CENTER);

    pnlMuestreo.revalidate();
    pnlMuestreo.repaint();
}
    
