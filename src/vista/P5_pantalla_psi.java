private void cargarDatosDeHoy() {
    try {
        if (idEncuesta <= 0) {
            limpiarPantalla();
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se recibió el identificador de la encuesta.");
            return;
        }

        unidades = dao.cargarUnidades();
        formas = dao.cargarFormasAdquisicion();
        lugares = dao.cargarLugaresCompra();
        frecuencias = dao.cargarFrecuenciasCompra();

        cmbUnidadMedida.removeAllItems();
        for (modelo.GastosDiariosDAO.OpcionCatalogo opcion : unidades) {
            cmbUnidadMedida.addItem(opcion.nombre);
        }

        cmbFormaAdquisicion.removeAllItems();
        for (modelo.GastosDiariosDAO.OpcionCatalogo opcion : formas) {
            cmbFormaAdquisicion.addItem(opcion.nombre);
        }

        cmbLugarCompra.removeAllItems();
        cmbLugarCompra.addItem("");
        for (modelo.GastosDiariosDAO.OpcionCatalogo opcion : lugares) {
            cmbLugarCompra.addItem(opcion.nombre);
        }

        cmbFrecuenciaCompra.removeAllItems();
        for (modelo.GastosDiariosDAO.OpcionCatalogo opcion : frecuencias) {
            cmbFrecuenciaCompra.addItem(opcion.nombre);
        }

        gastos = dao.cargarGastosHoy(idEncuesta);
        indiceActual = 0;

        if (gastos.isEmpty()) {
            limpiarPantalla();
            lblProducto.setText("No hay productos registrados hoy");
            btnEditar.setEnabled(false);
            jButton1.setEnabled(false);

            javax.swing.JOptionPane.showMessageDialog(this,
                    "No hay productos registrados hoy para esta encuesta.");
            return;
        }
scrGastosDiarios.setValues(
        0,
        1,
        0,
        Math.max(2, gastos.size())
);

scrGastosDiarios.setEnabled(gastos.size() > 1);
            // ==============================================================================================================

            btnEditar.setEnabled(true);
            jButton2.setEnabled(true);
            mostrarGastoActual();

    } catch (java.sql.SQLException ex) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "No fue posible cargar los productos: " + ex.getMessage(),
                "Error de base de datos",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}

private void mostrarGastoActual() {
    if (gastos.isEmpty()
            || indiceActual < 0
            || indiceActual >= gastos.size()) {
        return;
    }

    modelo.GastosDiariosDAO.GastoDiario gasto = gastos.get(indiceActual);

    txtNombreDelProducto.setText(gasto.nombreProducto);
    txtCantidadAdquirida.setText(String.valueOf(gasto.cantidad));
    txtEquivalencia.setText(
            gasto.equivalencia == null
                    ? ""
                    : String.valueOf(gasto.equivalencia));
    txtValor.setText(String.valueOf(gasto.valor));

    cmbUnidadMedida.setSelectedItem(
            buscarNombre(unidades, gasto.idUnidadMedida));

    cmbFormaAdquisicion.setSelectedItem(
            buscarNombre(formas, gasto.idFormaAdquisicion));

    if (gasto.idLugarCompra > 0) {
        cmbLugarCompra.setSelectedItem(
                buscarNombre(lugares, gasto.idLugarCompra));
    } else {
        cmbLugarCompra.setSelectedItem("");
    }

    cmbFrecuenciaCompra.setSelectedItem(
            buscarNombre(frecuencias, gasto.idFrecuenciaCompra));

    tipoGastoActual = gasto.tipoGasto;
    actualizarBotonesTipoGasto();

    lblProducto.setText(
            "Producto " + (indiceActual + 1) + " de " + gastos.size());

    bloquearEdicion();
scrGastosDiarios.setValue(0);
}

private String buscarNombre(
            java.util.List<modelo.GastosDiariosDAO.OpcionCatalogo> catalogo,
            int id) {

        for (modelo.GastosDiariosDAO.OpcionCatalogo opcion : catalogo) {
            if (opcion.id == id) {
                return opcion.nombre;
            }
        }

        return "";
    }

    private int buscarId(
            java.util.List<modelo.GastosDiariosDAO.OpcionCatalogo> catalogo,
            Object nombreSeleccionado) {

        if (nombreSeleccionado == null) {
            return 0;
        }

        for (modelo.GastosDiariosDAO.OpcionCatalogo opcion : catalogo) {
            if (opcion.nombre.equals(nombreSeleccionado.toString())) {
                return opcion.id;
            }
        }

        return 0;
    }

    private void bloquearEdicion() {

        edicionActiva = false;

        txtNombreDelProducto.setEditable(false);
        txtCantidadAdquirida.setEditable(false);
        txtEquivalencia.setEditable(false);
        txtValor.setEditable(false);

        cmbUnidadMedida.setEnabled(false);
        cmbFormaAdquisicion.setEnabled(false);
        cmbLugarCompra.setEnabled(false);
        cmbFrecuenciaCompra.setEnabled(false);

        btnHogar.setEnabled(false);
        btnPersonal.setEnabled(false);

        btnEditar.setEnabled(!gastos.isEmpty());
        jButton1.setEnabled(false);
        jButton2.setEnabled(!gastos.isEmpty());
    }

    private void habilitarEdicion() {
        if (gastos.isEmpty()) {
            return;
        }

        edicionActiva = true;

        txtNombreDelProducto.setEditable(false);
        txtCantidadAdquirida.setEditable(true);
        txtEquivalencia.setEditable(true);
        txtValor.setEditable(true);

        cmbUnidadMedida.setEnabled(true);
        cmbFormaAdquisicion.setEnabled(true);
        cmbLugarCompra.setEnabled(true);
        cmbFrecuenciaCompra.setEnabled(true);

        btnHogar.setEnabled(true);
        btnPersonal.setEnabled(true);

        btnEditar.setEnabled(false);
        jButton1.setEnabled(true);
    }

    private void actualizarBotonesTipoGasto() {
        if ("Hogar".equalsIgnoreCase(tipoGastoActual)) {
            btnHogar.setText("Hogar ✓");
            btnPersonal.setText("Personal");
        } else if ("Personal".equalsIgnoreCase(tipoGastoActual)) {
            btnHogar.setText("Hogar");
            btnPersonal.setText("Personal ✓");
        } else {
            btnHogar.setText("Hogar");
            btnPersonal.setText("Personal");
        }
    }

    private void guardarCambios() {
        if (!edicionActiva || gastos.isEmpty()) {
            return;
        }

        try {
            int cantidad = Integer.parseInt(
                    txtCantidadAdquirida.getText().trim());

            int valor = Integer.parseInt(
                    txtValor.getText().trim());

            String textoEquivalencia = txtEquivalencia.getText().trim();
            Integer equivalencia = textoEquivalencia.isEmpty()
                    ? null
                    : Integer.valueOf(textoEquivalencia);

            if (cantidad <= 0 || valor < 0
                    || (equivalencia != null && equivalencia < 0)) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "La cantidad debe ser mayor que cero. "
                        + "El valor y la equivalencia no pueden ser negativos.");
                return;
            }

            int idUnidad = buscarId(
                    unidades, cmbUnidadMedida.getSelectedItem());

            int idForma = buscarId(
                    formas, cmbFormaAdquisicion.getSelectedItem());

            int idLugar = buscarId(
                    lugares, cmbLugarCompra.getSelectedItem());

            int idFrecuencia = buscarId(
                    frecuencias, cmbFrecuenciaCompra.getSelectedItem());

            if (idUnidad <= 0 || idForma <= 0 || idFrecuencia <= 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Selecciona la unidad de medida, la forma de adquisición "
                        + "y la frecuencia de compra.");
                return;
            }

            if (tipoGastoActual == null
                    || (!tipoGastoActual.equalsIgnoreCase("Hogar")
                    && !tipoGastoActual.equalsIgnoreCase("Personal"))) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Selecciona el tipo de gasto: Hogar o Personal.");
                return;
            }

            modelo.GastosDiariosDAO.GastoDiario gasto =
                    gastos.get(indiceActual);

            boolean actualizado = dao.actualizarGasto(
                    gasto.id,
                    idEncuesta,
                    cantidad,
                    equivalencia,
                    valor,
                    tipoGastoActual,
                    idUnidad,
                    idForma,
                    idLugar,
                    idFrecuencia
            );

            if (actualizado) {
                gasto.cantidad = cantidad;
                gasto.equivalencia = equivalencia;
                gasto.valor = valor;
                gasto.tipoGasto = tipoGastoActual;
                gasto.idUnidadMedida = idUnidad;
                gasto.idFormaAdquisicion = idForma;
                gasto.idLugarCompra = idLugar;
                gasto.idFrecuenciaCompra = idFrecuencia;

                bloquearEdicion();
                mostrarGastoActual();

                javax.swing.JOptionPane.showMessageDialog(this,
                        "Los cambios se guardaron correctamente.");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "No se actualizó el producto. Comprueba que pertenezca "
                        + "a esta encuesta y que esté registrado hoy.");
            }

        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La cantidad, el valor y la equivalencia deben ser números enteros.");
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error al guardar los cambios: " + ex.getMessage(),
                    "Error de base de datos",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiarPantalla() {
        txtNombreDelProducto.setText("");
        txtCantidadAdquirida.setText("");
        txtEquivalencia.setText("");
        txtValor.setText("");

        cmbUnidadMedida.setSelectedIndex(-1);
        cmbFormaAdquisicion.setSelectedIndex(-1);
        cmbLugarCompra.setSelectedIndex(-1);
        cmbFrecuenciaCompra.setSelectedIndex(-1);

        tipoGastoActual = null;
        actualizarBotonesTipoGasto();
        bloquearEdicion();
    }

    private void salirDePantalla() {
        if (pantallaAnterior != null) {
            pantallaAnterior.setVisible(true);
        }

        dispose();
    }

    private void continuarProducto() {

        if (edicionActiva) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Primero guarda los cambios del producto actual.");
            return;
        }

        if (gastos.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No hay productos para mostrar.");
            return;
        }

if (indiceActual < gastos.size() - 1) {
            indiceActual++;
            mostrarGastoActual();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Has llegado al último producto registrado hoy.");
        }
    }
