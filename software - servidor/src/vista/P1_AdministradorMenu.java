// Mostrar un panel con su barra de desplazamiento
public void mostrarContenido(JPanel contenido, JScrollBar barra) {

    pnlInterfaz.removeAll();

    pnlInterfaz.setLayout(new BorderLayout());

    pnlInterfaz.add(contenido, BorderLayout.CENTER);

    pnlInterfaz.add(barra, BorderLayout.EAST);

    pnlInterfaz.revalidate();
    pnlInterfaz.repaint();
}

