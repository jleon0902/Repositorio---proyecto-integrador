    private void configurarTabla(
            javax.swing.JTable tabla,
            javax.swing.JScrollPane scroll
    ) {
        tabla.setDefaultEditor(Object.class, null);
        tabla.getTableHeader().setReorderingAllowed(false);
        tabla.getTableHeader().setResizingAllowed(false);
        tabla.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF);

        scroll.setHorizontalScrollBarPolicy(
                javax.swing.JScrollPane.HORIZONTAL_SCROLLBAR_ALWAYS
        );
        scroll.setVerticalScrollBarPolicy(
                javax.swing.JScrollPane.VERTICAL_SCROLLBAR_ALWAYS
        );

        ajustarAnchoColumnas(tabla);

        tabla.getModel().addTableModelListener(e -> {
            javax.swing.SwingUtilities.invokeLater(() -> {
                ajustarAnchoColumnas(tabla);
            });
        });
    }

    private void ajustarAnchoColumnas(javax.swing.JTable tabla) {
        javax.swing.table.TableColumnModel modeloColumnas = tabla.getColumnModel();

        for (int columna = 0; columna < tabla.getColumnCount(); columna++) {
            javax.swing.table.TableColumn columnaActual = modeloColumnas.getColumn(columna);
            int anchoMinimo = columnaActual.getMinWidth();

            if (anchoMinimo == 15) {
                anchoMinimo = columnaActual.getWidth();
                columnaActual.setMinWidth(anchoMinimo);
            }

            javax.swing.table.TableCellRenderer renderizadorEncabezado =
                    tabla.getTableHeader().getDefaultRenderer();

            java.awt.Component componenteEncabezado =
                    renderizadorEncabezado.getTableCellRendererComponent(
                            tabla,
                            columnaActual.getHeaderValue(),
                            false,
                            false,
                            -1,
                            columna
                    );

            int anchoNecesario = componenteEncabezado.getPreferredSize().width + 20;

            for (int fila = 0; fila < tabla.getRowCount(); fila++) {
                java.awt.Component componente =
                        tabla.prepareRenderer(
                                tabla.getCellRenderer(fila, columna),
                                fila,
                                columna
                        );

                int anchoCelda = componente.getPreferredSize().width + 20;
                anchoNecesario = Math.max(anchoNecesario, anchoCelda);
            }

            int anchoFinal = Math.max(anchoMinimo, anchoNecesario);
            columnaActual.setPreferredWidth(anchoFinal);
            columnaActual.setWidth(anchoFinal);
        }

        tabla.getTableHeader().revalidate();
        tabla.revalidate();
        tabla.repaint();
    }
    
